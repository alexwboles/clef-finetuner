"""LoRA training pipeline for Clef-flash.

Three modes:
  --dry-run : validate inputs, print the exact training plan, touch nothing.
  --mock    : train a MockAdapter on this machine (full pipeline, no GPU).
  (default) : generate run_lora.py + lora_config.json for a GPU machine
              (transformers + peft + bitsandbytes). Nothing is executed here.
"""
from __future__ import annotations

import json
import os
from dataclasses import asdict, dataclass

from .dataset import Example, split_dataset
from .mock import MockAdapter

BASE_MODEL = "cloudflare/clef-flash"  # HF repo per release announcement

DEFAULTS = {
    "lora_r": 16,
    "lora_alpha": 32,
    "lora_dropout": 0.05,
    "target_modules": ["q_proj", "k_proj", "v_proj", "o_proj"],
    "epochs": 3,
    "lr": 2e-4,
    "batch_size": 4,
    "grad_accum": 4,
    "eval_frac": 0.1,
    "seed": 42,
    "load_in_4bit": True,
    "bf16": True,
    "max_seq_len": 4096,
}


@dataclass
class TrainPlan:
    n_train: int
    n_eval: int
    steps_per_epoch: int
    total_steps: int
    effective_batch: int
    est_vram_gb: float
    config: dict

    def describe(self) -> str:
        c = self.config
        lines = [
            "Training plan (Clef-flash LoRA)",
            f"  base model      : {BASE_MODEL}",
            f"  train / eval    : {self.n_train} / {self.n_eval} examples",
            f"  LoRA            : r={c['lora_r']} alpha={c['lora_alpha']} "
            f"dropout={c['lora_dropout']} targets={','.join(c['target_modules'])}",
            f"  precision       : {'4-bit base + bf16' if c['load_in_4bit'] else 'bf16'}",
            f"  epochs / lr     : {c['epochs']} / {c['lr']}",
            f"  eff. batch      : {self.effective_batch} "
            f"({c['batch_size']} x {c['grad_accum']} accum)",
            f"  total steps     : {self.total_steps}",
            f"  est. VRAM       : ~{self.est_vram_gb:.1f} GB "
            f"(fits a 24 GB consumer GPU at 4-bit)",
            f"  max seq len     : {c['max_seq_len']}",
        ]
        return "\n".join(lines)


def build_plan(examples: list[Example], config: dict) -> TrainPlan:
    train, ev = split_dataset(
        examples, eval_frac=config["eval_frac"], seed=config["seed"]
    )
    eff_batch = config["batch_size"] * config["grad_accum"]
    steps_per_epoch = max(1, (len(train) + eff_batch - 1) // eff_batch)
    total_steps = steps_per_epoch * config["epochs"]
    # Rough estimate: 9B params -> 4-bit base ~4.5GB + LoRA + optimizer states.
    est_vram = 4.5 + (config["lora_r"] / 16) * 1.2 + (config["max_seq_len"] / 4096) * 2.0
    return TrainPlan(
        n_train=len(train),
        n_eval=len(ev),
        steps_per_epoch=steps_per_epoch,
        total_steps=total_steps,
        effective_batch=eff_batch,
        est_vram_gb=round(est_vram, 1),
        config=config,
    )


def train_mock(examples: list[Example], out_dir: str, config: dict) -> str:
    train, _ = split_dataset(
        examples, eval_frac=config["eval_frac"], seed=config["seed"]
    )
    adapter = MockAdapter.train(train)
    return adapter.save(out_dir)


RUN_LORA_TEMPLATE = '''#!/usr/bin/env python3
"""Generated by clef-tuner. Run on a GPU machine:
    pip install torch transformers peft bitsandbytes datasets
    python run_lora.py --data /path/to/dataset.jsonl --out ./adapter
"""
import argparse, json
from datasets import Dataset
from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig, TrainingArguments
from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
from trl import SFTTrainer  # pip install trl

BASE_MODEL = "cloudflare/clef-flash"

def encode(ex):
    # Mirror of clef-tuner record encoding: state + typed question -> prompt,
    # answer -> target label token. Adapt to the release's joint_schema_model
    # helpers if your checkpoint ships them.
    q = ex["question"]
    schema = {"type": q["type"], "name": q["name"]}
    if q["type"] == "choice":
        schema["options"] = q["options"]
    elif q["type"] == "score":
        schema["levels"] = q["levels"]
    state = ex["state"]["text"]
    if ex["state"].get("json"):
        state += "\\n" + json.dumps(ex["state"]["json"])
    prompt = f"STATE: {state}\\nQUESTION: {json.dumps(schema)}\\nDECISION:"
    return {"text": prompt + " " + ex["answer"]}

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--config", default="lora_config.json")
    args = ap.parse_args()
    cfg = json.load(open(args.config))
    rows = [json.loads(l) for l in open(args.data) if l.strip()]
    ds = Dataset.from_list([encode(r) for r in rows])
    bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_compute_dtype="bfloat16")
    model = AutoModelForCausalLM.from_pretrained(BASE_MODEL, quantization_config=bnb, device_map="auto")
    model = prepare_model_for_kbit_training(model)
    tok = AutoTokenizer.from_pretrained(BASE_MODEL)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    peft_cfg = LoraConfig(r=cfg["lora_r"], lora_alpha=cfg["lora_alpha"],
                          lora_dropout=cfg["lora_dropout"],
                          target_modules=cfg["target_modules"],
                          task_type="CAUSAL_LM")
    model = get_peft_model(model, peft_cfg)
    targs = TrainingArguments(output_dir=args.out, num_train_epochs=cfg["epochs"],
                              learning_rate=cfg["lr"],
                              per_device_train_batch_size=cfg["batch_size"],
                              gradient_accumulation_steps=cfg["grad_accum"],
                              bf16=True, logging_steps=10, save_strategy="epoch")
    SFTTrainer(model=model, tokenizer=tok, train_dataset=ds,
               args=targs, dataset_text_field="text").train()
    model.save_pretrained(args.out)
    print("adapter saved to", args.out)

if __name__ == "__main__":
    main()
'''


def generate_real_training(out_dir: str, config: dict) -> list[str]:
    os.makedirs(out_dir, exist_ok=True)
    cfg_path = os.path.join(out_dir, "lora_config.json")
    with open(cfg_path, "w", encoding="utf-8") as fh:
        json.dump(config, fh, indent=2)
    script_path = os.path.join(out_dir, "run_lora.py")
    with open(script_path, "w", encoding="utf-8") as fh:
        fh.write(RUN_LORA_TEMPLATE)
    os.chmod(script_path, 0o755)
    return [cfg_path, script_path]
